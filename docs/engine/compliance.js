// 否定句不算：「我不能保證收入」「絕對不可以退佣」「保險不是存錢」是正確的說法，不能被當成違規擋下來。
// 判斷方式：命中字眼的前面幾個字有否定詞，就略過這一次命中，再找同一句後面有沒有別的命中。
const NEG = /(不|沒|無法|沒辦法|沒有人|不能|不會|不可以|不可能|不得|禁止|嚴禁|別|不要)[^，。！？]{0,4}$/;
function hit(re, text) {
  const g = new RegExp(re.source, re.flags.includes('g') ? re.flags : re.flags + 'g');
  for (const m of text.matchAll(g)) {
    if (!NEG.test(text.slice(Math.max(0, m.index - 8), m.index))) return true;
  }
  return false;
}

export function checkCompliance(text) {
  if (!text) return { level: 'none', hits: [] };
  const hits = [];
  for (const r of HIGH) if (hit(r.re, text)) hits.push({ type: r.type, law: r.law, why: r.why, level: 'high' });
  for (const r of WARN) if (hit(r.re, text)) hits.push({ type: r.type, law: r.law, why: r.why, level: 'warn' });
  const level = hits.some(h => h.level === 'high') ? 'high' : hits.length ? 'warn' : 'none';
  return { level, hits };
}

// 高風險 → 演練當下暫停並說明（GPT 版：及時阻止，演練後再點名指正）
export function interventionMessage(hits) {
  const h = hits.filter(x => x.level === 'high');
  const list = h.map(x => `・${x.type}（${x.law}）：${x.why}`).join('\n');
  return `⚠️ 合規提醒（演練暫停）\n\n你剛才的說法可能違反規定：\n${list}\n\n請換一個不涉及保證收入、利益交換或違規做法的說法，再繼續演練。`;
}
