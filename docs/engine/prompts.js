// 招募對象會自然講到「業務員」「保險業務」，所以不像 AI業務教練那樣擋「業務員」這個詞。
const BREAK = /(身為|作為).{0,4}(AI|人工智慧|招募對象|角色)|我是.{0,4}(AI|語言模型|助理|教練)|建議你|你可以嘗試|演練|模擬|練習中|評分|加油/;

export function validateRoleplay(say) {
  if (!say || typeof say !== 'string') return null;
  let s = say.replace(/^["「『]|["」』]$/g, '').trim();
  // 代稱符號唸出來會變成「圈圈」：「我是○○。」整段拿掉，其他地方的符號直接刪
  s = s.replace(/(我是|我叫)[○〇]{2,}[，。,！!]?/g, '').replace(/[○〇]{2,}(先生|小姐|老師)?/g, '').replace(/\s{2,}/g, ' ').trim();
  if (!s || BREAK.test(s)) return null;
  if (s.length > 120) {
    const cut = s.slice(0, 120);
    const i = Math.max(cut.lastIndexOf('。'), cut.lastIndexOf('？'), cut.lastIndexOf('！'));
    s = i > 20 ? cut.slice(0, i + 1) : cut;
  }
  return s;
}
