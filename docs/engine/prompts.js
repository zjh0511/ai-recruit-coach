export function roleplayTurn({ history, userText, trust, guidance, maxGuidance, mustDecline = false, gentle = false, notYet = null, mode = 'call' }) {
  const convo = history.map(t => `${t.speaker === 'user' ? '對方' : '你'}：${t.text}`).join('\n');
  let extra = '';
  if (mustDecline) {
    // GPT 版規則：引導三次後仍無法有效練習，就像真實招募對象那樣委婉拒絕
    extra = `\n\n【本回合額外指示】你已經引導對方 ${guidance} 次，他還是沒有把來意講清楚、談話沒有進展。`
      + '如果他這一句仍然沒有講清楚或沒有回應到你，請像真實的人那樣委婉但明確地拒絕、結束這次談話，並把 declined 設為 true；'
      + '如果他這一句終於講清楚了，就正常回應。';
  } else if (guidance > 0 && gentle) {
    extra = '\n\n【本回合額外指示】對方前面講得不太順。請用你本人的身分善意地幫他接話，給他一個容易回答的具體問題，不要不耐煩。';
  } else if (guidance > 0 && guidance < maxGuidance) {
    extra = '\n\n【本回合額外指示】對方前面講得不清楚。用你本人的身分自然追問，例如「你找我什麼事？」，不要教他。';
  }
  // 程式不會認可的答應，也不要讓對方嘴上答應——否則畫面上的結果和對話對不起來
  if (notYet === 'early') extra += '\n（談話才剛開始，就算他現在提出邀約，你也還不會答應，可以說想先多了解一點；commit 一律填 "none"。）';
  if (notYet === 'trust') extra += '\n（你現在對他的信任還不夠，就算他提出邀約，你也還不會答應；commit 一律填 "none"。）';

  return `【目前你對他的信任度】${trust}／100

【到目前為止的對話】
${convo || '（對話剛開始）'}

【對方剛剛說】
${userText}${extra}

${mode === 'call' ? '（提醒：你們現在是在講電話，沒有見面。）\n' : ''}依你的人設與絕對規則回應，只輸出 JSON。`;
}

